hl.on("hyprland.start", function()
    -- swaync retired 2026-08-20: the shell is the notification daemon
    -- (Notifs.qml claims org.freedesktop.Notifications). The unit is
    -- disabled and the stow package deleted -- do not re-enable it, two
    -- daemons race for the bus name and the loser wedges its unit.
    -- waybar and hyprpaper retired 2026-08-19: the status bar is the
    -- Quickshell surface (Bar.qml, handoff turn 13b) and the wallpaper is
    -- the battle field (Wallpaper.qml, turn 16a), which owns the background
    -- layer itself. Their configs stay in the repo but nothing starts them.
    hl.exec_cmd("hypridle")

    -- Keyboard backlight dark at login. Nothing in userspace was choosing its
    -- level before this line: the Fn keys are handled in-kernel by
    -- asus_nb_wmi, so whatever the EC powered up with simply persisted across
    -- the session. Touch typing does not need it lit, and the panel is the
    -- only backlight worth spending battery on. Fn+F2/F3 still steps it back
    -- up on demand -- this only sets the starting point, and only at a real
    -- login, like everything else in this block.
    hl.exec_cmd("brightnessctl -d asus::kbd_backlight set 0")

    -- The Quickshell shell, currently hosting the RPG launcher (SUPER + space).
    -- -d detaches it from this process. It stays resident with no window
    -- shown: the launcher surface is built once at startup and toggled over
    -- IPC, so opening it costs a frame rather than a process start, and
    -- nothing in it polls or animates while it is hidden.
    hl.exec_cmd("qs -d")

    -- Bring up the session's systemd units.
    --
    -- This used to read "that target never activates under this launcher, so
    -- start the unit directly", and started hyprpolkitagent.service and
    -- hyprsunset.service by name. That was never quite the real story:
    -- hyprsunset.service has Requires=graphical-session.target, so starting
    -- hyprsunset is what dragged the target up, and the target in turn started
    -- the polkit agent, the xdg portals and everything else in its .wants
    -- directory. The whole session hung off a side effect of one
    -- blue-light-filter unit.
    --
    -- graphical-session.target cannot be started by name -- it sets
    -- RefuseManualStart=yes and only comes up as someone's dependency. So
    -- hyprland-session.target exists to be that someone. See
    -- ~/.config/systemd/user/hyprland-session.target.
    hl.exec_cmd("systemctl --user start hyprland-session.target")

    hl.exec_cmd("wl-paste --type text --watch cliphist store")   -- text only
    hl.exec_cmd("wl-paste --type image --watch cliphist store")  -- images only

    -- Keep the selection alive after the source window closes. Without this,
    -- Wayland drops the clipboard when the owning client exits and a plain
    -- Ctrl+V pastes nothing. "regular" only -- covering primary as well is
    -- known to fight cliphist over the middle-click selection.
    hl.exec_cmd("wl-clip-persist --clipboard regular")

    -- was: exec-once = [workspace 1 silent] firefox
    -- Dispatcher prefixes are now the rules table on exec_cmd.
    hl.dispatch(hl.dsp.exec_cmd("firefox", { workspace = "1 silent" }))
    hl.dispatch(hl.dsp.exec_cmd(terminal,  { workspace = "2 silent" }))
end)


