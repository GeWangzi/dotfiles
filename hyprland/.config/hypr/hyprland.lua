-- Window border colours come from the active skin rather than being written
-- here. ~/.local/state/skins/skin.lua is generated by `skinctl` and returns a
-- flat table of bare rrggbb strings; the source it is generated from is
-- ~/.config/skins/skins.toml.
--
-- The load is wrapped in pcall on purpose. This file is the compositor's
-- entire configuration, and a missing or half-written skin.lua raising out of
-- a bare dofile would take the whole session down to a black screen on a
-- machine whose recovery path is a TTY. Falling back to the Ember values
-- below costs nothing and cannot fail.
local skin = (function()
    local state = os.getenv("XDG_STATE_HOME") or (os.getenv("HOME") .. "/.local/state")
    local ok, loaded = pcall(dofile, state .. "/skins/skin.lua")
    if ok and type(loaded) == "table" and loaded.outer then
        return loaded
    end
    return {
        outer   = "f96b69",  -- Ember: the sun disc
        accent  = "e8a04a",  -- Ember: amber
        inner   = "482b2c",  -- Ember: the horizon band
        shadow  = "0f0c0e",
    }
end)()

-- Hyprland wants rgba(rrggbbaa); the skin table stores rrggbb.
local function rgba(token, alpha)
    return "rgba(" .. token .. (alpha or "ff") .. ")"
end


